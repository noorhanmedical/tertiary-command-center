// QA: Phase 1 canonical ID registry (Batch C2).
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const failures = [];
function read(rel) { const abs = path.join(root, rel); if (!fs.existsSync(abs)) return null; return fs.readFileSync(abs, "utf8"); }

const DOC = "docs/architecture/phase-1-canonical-id-registry.md";
const c = read(DOC);
if (c === null) failures.push(`Missing file: ${DOC}`);
else {
  const ids = [
    "patientId", "patientScreeningId", "executionCaseId", "batchId",
    "ancillaryId", "assignmentId", "taskId", "triageCaseId",
    "journeyEventId", "documentId", "signatureId",
    "billingReadinessId", "invoiceId", "ringCentralCallId",
  ];
  for (const id of ids) if (!c.includes(id)) failures.push(`Missing ID "${id}" in ${DOC}`);
  const fields = [
    "Source owner:", "Generated by:", "Consumed by:",
    "Write owner:", "Read consumers:", "No-split-brain rule:",
  ];
  for (const f of fields) {
    const count = (c.match(new RegExp(f.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g")) ?? []).length;
    if (count < 10) failures.push(`Field "${f}" appears only ${count} times; expected per-ID coverage`);
  }
  for (const n of [
    "Plexus IQ does NOT mint",
    "Admin Review does NOT mint",
    "Team Portal CONSUMES IDs",
    "RingCentral is telephony adapter ONLY",
  ]) if (!c.includes(n)) failures.push(`Missing "${n}" in ${DOC}`);
}

if (failures.length > 0) {
  console.error("Phase 1 canonical ID registry QA failed:");
  for (const f of failures) console.error(`- ${f}`);
  process.exit(1);
}
console.log("Phase 1 canonical ID registry QA passed.");
